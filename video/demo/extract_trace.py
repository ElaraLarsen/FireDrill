"""Turn the real live recording (docs/evidence/live-switch-idempotency-race.jsonl) into src/liveTrace.ts.

Only frames that exist in the recording are used; nothing is invented. Lines are the same ones the
dashboard console prints (time, who, text).
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
frames = [json.loads(l) for l in (root / "docs/evidence/live-switch-idempotency-race.jsonl").read_text().splitlines()]


def clock(ts: str) -> str:
    return re.search(r"T(\d\d:\d\d:\d\d)", ts).group(1)


def short(sha: str) -> str:
    return sha[:7]


out = []
for f in frames:
    d = f["data"]
    who = f["actor"].get("name", "?")
    k = f["kind"]
    if k == "room_message" and f["actor"].get("role") != "gate":
        body = d["body"].split("\n")[0]
        m = re.match(r"@firedrill-gate (SUBMIT|ATTACK|APPROVE) (\S+)(?: (\S+))?", body)
        if m:
            verb, a, b = m.groups()
            text = f"{verb} {a}" + (f" {b[:7]}" if b and verb != "APPROVE" else "")
            out.append({"time": clock(f["ts"]), "who": who, "ink": "human", "text": text, "step": "say"})
    elif k == "check" and d["against"] != "reference":
        ok = d["status"] == "pass"
        name = d["name"].replace("checks/", "").replace(".py", "")
        out.append({"time": clock(f["ts"]), "who": who, "ink": "pass" if ok else "fail", "text": f"{'✓' if ok else '✗'} {name}", "note": f"{d.get('duration_ms', '?')}ms", "step": "check"})
    elif k == "verdict":
        checks = [c for c in d["checks"] if c["against"] != "reference"]
        ok = sum(1 for c in checks if c["status"] == "pass")
        out.append({"time": clock(f["ts"]), "who": who, "ink": "pass" if d["result"] == "GREEN" else "fail", "text": f"verdict {d['verdict_id']} {d['result']}", "note": f"{ok}/{len(checks)} checks on the patch passed", "step": "verdict"})
    elif k == "signoff":
        out.append({"time": clock(f["ts"]), "who": d["by"], "ink": "human", "text": f"sign-off {d['verdict_id']}", "note": "pinned to the Switch participant id", "step": "signoff"})
    elif k == "merge":
        out.append({"time": clock(f["ts"]), "who": who, "ink": "pass", "text": f"merged into main @ {short(d['main_sha'])}", "note": d["verdict_id"], "step": "merge"})

ts = "// Generated by extract_trace.py from docs/evidence/live-switch-idempotency-race.jsonl (a real run on Switch 0.31.0).\n"
ts += "export type TraceLine = { time: string; who: string; ink: \"human\" | \"pass\" | \"fail\"; text: string; note?: string; step: string };\n"
ts += "export const liveTrace: TraceLine[] = " + json.dumps(out, indent=2, ensure_ascii=False) + ";\n"
(Path(__file__).parent / "src/liveTrace.ts").write_text(ts)
print(len(out), "lines")
for o in out:
    print(o["time"], o["who"], o["text"], o.get("note", ""))
